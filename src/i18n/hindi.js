// t('Products ({count})', { count: 3 }) fills the placeholders a string needs. Values are
// inserted as text, never as markup, and a key that is missing renders the English source.
export function translate(lang, key, vars) {
  let out = lang === 'hi' ? HINDI[key] || key : key;
  if (vars) {
    for (const [name, value] of Object.entries(vars)) out = out.split(`{${name}}`).join(String(value));
  }
  return out;
}
